package eu.wohlben.qits.mirror.api;

import static io.restassured.RestAssured.given;

import io.quarkus.test.junit.QuarkusTest;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import org.junit.jupiter.api.Test;

/**
 * Writes {@code docs/openapi.yml} as a side effect of the suite, the same way the sibling services
 * do. Checking the document in is what turns an API change into a reviewable diff instead of
 * something a caller discovers at runtime.
 *
 * <p>This is a test only because {@code @QuarkusTest} is the cheapest way to stand the application
 * up and read its own {@code /mirror/q/openapi} — that path is {@code
 * quarkus.http.non-application-root-path}, not {@code quarkus.rest.path}, so it moves with the
 * former alone. The status check is the one assertion: the document is served at that path.
 * Everything else is the diff.
 *
 * <p>The document is two sources merged. The admin API at {@code /mirror/api} is JAX-RS, and its
 * operations come from their {@code @Operation} annotations. The wire doors — {@code
 * getMavenMetadata} and {@code getNpmPackument}, the two reads qits-maintenance makes through the
 * caches — are Vert.x routes from the qits-registries jars, which no annotation describes, so they
 * come from {@code src/main/resources/META-INF/openapi.yaml}. The rest of the protocol grammar stays
 * out: its clients are mvn, npm and docker, not qits repositories.
 *
 * <p>The test classpath is indexed too, so any {@code @Path} resource under {@code src/test} would
 * land in the committed document unless it is {@code @Operation(hidden = true)}. There is none
 * today; one added later carries that annotation.
 */
@QuarkusTest
public class OpenApiSchemaExportTest {

  @Test
  public void exportOpenApiSchema() throws Exception {
    String schema =
        given().when().get("/mirror/q/openapi").then().statusCode(200).extract().asString();

    // A single-module project: the working directory is the repository root.
    Path docsDir = Paths.get("docs");
    if (!Files.exists(docsDir)) {
      Files.createDirectories(docsDir);
    }

    String header =
        "# THIS FILE IS GENERATED BY OpenApiSchemaExportTest — DO NOT EDIT MANUALLY.\n"
            + "# Run `./mvnw test -Dtest=OpenApiSchemaExportTest"
            + " -Dsurefire.failIfNoSpecifiedTests=false` to regenerate.\n";

    Files.writeString(docsDir.resolve("openapi.yml"), header + schema);
  }
}
